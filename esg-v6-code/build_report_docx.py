def full_ctx(gid, prefix):
    """Insert the image's COMPLETE context pool, verbatim, plus its own caption."""
    g = _GROUPS[gid]
    pool = g.get("context_pool", [])
    p(f"完整本地上下文（池，共 {len(pool)} 段，原文照录）", bold=True)
    if not pool:
        p("（本地池为空，无叙述段。）")
    for i, c in enumerate(pool):
        p(f"[{i+1}] {c.get('text','')}")
    caps = []
    for im in g.get("images", []):
        if im.get("filename", "").startswith(prefix):
            caps = im.get("caption_candidates", []) or []
    if caps:
        p(f"本图图注（共 {len(caps)} 条，原文照录）：")
        for j, cp in enumerate(caps):
            p(f"（图注 {j+1}）{cp}")
    else:
        p("本图无图注。")


